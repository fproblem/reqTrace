/** Тесты нормализации текста (v1.5.9): сравнение «это тот же текст?» для
 * валидационного гарда слоя (текст под координатами ↔ текст маркера).
 * Поисковых функций больше нет — координаты привязок поддерживает сервер.
 */
import { strippedText, strippedEquals } from './highlightMatching';

describe('strippedText / strippedEquals', () => {
  it('убирает все пробелы и переносы', () => {
    expect(strippedText('  a\n b\tc ')).toBe('abc');
  });

  it('равенство игнорирует различия в вёрстке, но не в символах', () => {
    expect(strippedEquals('Текст для удаления', 'Текст  для\nудаления')).toBe(true);
    expect(strippedEquals('Текст для удаления', 'Текст для удаленияX')).toBe(false);
    expect(strippedEquals('Уровень 3 — пункт два.', 'Уровень 3.1 — пункт один.')).toBe(false);
  });

  it('чужой блок под якорем не проходит сверку', () => {
    // Правило гарда renderAtAnchors: текст под координатами обязан совпасть
    // с текстом маркера — иначе метка не рисуется (рассинхрон).
    expect(strippedEquals('Цитата с прямым текстом без абзаца.', 'Текст для удаления')).toBe(false);
  });
});

describe('невидимые символы (Confluence вставляет их при перенаборе текста)', () => {
  it('zero-width space и soft hyphen игнорируются наравне с пробелами', () => {
    expect(strippedEquals('под\u200Bзаголовок', 'подзаголовок')).toBe(true);
    expect(strippedText('чет\u00ADвертого\uFEFF')).toBe('четвертого');
  });

  it('текст с невидимым символом внутри считается ТЕМ ЖЕ текстом', () => {
    expect(strippedEquals(
      'Текст под под\u200Bзаголовок четвертого уровня.',
      'Текст под подзаголовок четвертого уровня.',
    )).toBe(true);
  });
});
