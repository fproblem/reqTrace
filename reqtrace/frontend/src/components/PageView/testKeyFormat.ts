// Мягкая проверка ключа теста. Из ключей строятся ссылки «<jira>/browse/<ключ>»,
// поэтому опечатка (кириллическая буква-двойник, пробел, потерянный дефис) —
// это битая ссылка. Формат ключа Jira: латинский префикс проекта с буквы,
// дефис, номер. Проверка ничего не запрещает — только подсвечивает: регистр
// не считается ошибкой (Jira открывает /browse/proj-1 как PROJ-1).
const JIRA_KEY_RE = /^[A-Z][A-Z0-9_]*-\d+$/;

export function isLikelyJiraKey(key: string): boolean {
  return JIRA_KEY_RE.test(key.toUpperCase());
}
