def py_module_name(path: Path) -> Tuple[str, Path]:
    """Return (dotted module name, source-root dir) for a .py file."""
    stem = path.stem
    pkg_parts: List[str] = []
    cur = path.parent
    while (cur / "__init__.py").exists():
        pkg_parts.append(cur.name)
        parent = cur.parent
        if parent == cur:
            break
        cur = parent
    pkg_parts.reverse()
    if stem == "__init__":
        mod = ".".join(pkg_parts)
    else:
        mod = ".".join(pkg_parts + [stem])
    return mod, cur


def arg_names(a: ast.arguments, drop_self: bool = False) -> str:
    names: List[str] = []
    posonly = getattr(a, "posonlyargs", [])
    for x in list(posonly) + list(a.args):
        names.append(x.arg)
    if a.vararg:
        names.append("*" + a.vararg.arg)
    for x in a.kwonlyargs:
        names.append(x.arg)
    if a.kwarg:
        names.append("**" + a.kwarg.arg)
    if drop_self and names and names[0] in ("self", "cls"):
        names = names[1:]
    return ", ".join(names)


def _str_const(node: ast.AST) -> Optional[str]:
    if isinstance(node, ast.Constant) and isinstance(node.value, str):
        return node.value
    return None


def analyze_py(path: Path, rel: str, src: str) -> Tuple[Node, List[Tuple[str, str, List[str], int, bool]]]:
    """
    Returns (Node, raw_import_specs).
    raw_import_specs entries: (kind, module, names, level, is_pkg)
       kind = "import" | "from"
    """
    node = Node(id=rel, lang="py", layer=detect_layer(rel, "py"),
                loc=src.count("\n") + 1, tokens=max(1, len(src) // 4))
    raw_imports: List[Tuple[str, str, List[str], int, bool]] = []
    is_pkg = path.stem == "__init__"
    node.is_script = '__name__' in src and '__main__' in src

    try:
        tree = ast.parse(src, filename=str(path))
    except SyntaxError:
        return node, raw_imports

    ext_roots: Set[str] = set()

    # First pass: find APIRouter / app prefixes for route resolution
    router_prefix: Dict[str, str] = {}
    for stmt in tree.body:
        if isinstance(stmt, ast.Assign) and isinstance(stmt.value, ast.Call):
            fn = stmt.value.func
            fn_name = fn.id if isinstance(fn, ast.Name) else (fn.attr if isinstance(fn, ast.Attribute) else "")
            if fn_name in ("APIRouter", "FastAPI"):
                prefix = ""
                for kw in stmt.value.keywords:
                    if kw.arg == "prefix":
                        prefix = _str_const(kw.value) or ""
                for tgt in stmt.targets:
                    if isinstance(tgt, ast.Name):
                        router_prefix[tgt.id] = prefix

    def route_from_decorator(dec: ast.AST) -> Optional[str]:
        if not isinstance(dec, ast.Call):
            return None
        f = dec.func
        if not isinstance(f, ast.Attribute):
            return None
        if not isinstance(f.value, ast.Name):
            return None
        method = f.attr.upper()
        if method not in ("GET", "POST", "PUT", "DELETE", "PATCH", "HEAD", "OPTIONS"):
            return None
        var = f.value.id
        if var not in router_prefix:
            return None
        path_arg = ""
        if dec.args:
            path_arg = _str_const(dec.args[0]) or ""
        full = (router_prefix[var] + path_arg) or "/"
        return f"{method} {full}"

    # Imports + top-level symbols
    for stmt in tree.body:
        if isinstance(stmt, ast.Import):
            mods = [a.name for a in stmt.names]
            for m in mods:
                ext_roots.add(m.split(".")[0])
            raw_imports.append(("import", "", mods, 0, is_pkg))

        elif isinstance(stmt, ast.ImportFrom):
            mod = stmt.module or ""
            names = [a.name for a in stmt.names]
            if stmt.level == 0 and mod:
                ext_roots.add(mod.split(".")[0])
            raw_imports.append(("from", mod, names, stmt.level, is_pkg))

        elif isinstance(stmt, (ast.FunctionDef, ast.AsyncFunctionDef)):
            sig = f"{stmt.name}({arg_names(stmt.args)})"
            node.symbols.append(Symbol("func", stmt.name, sig, stmt.lineno))
            for dec in stmt.decorator_list:
                r = route_from_decorator(dec)
                if r:
                    node.routes.append(r)

        elif isinstance(stmt, ast.ClassDef):
            bases = []
            for b in stmt.bases:
                try:
                    bases.append(ast.unparse(b))
                except Exception:
                    pass
            sym = Symbol("class", stmt.name, "", stmt.lineno, extra=", ".join(bases))
            node.symbols.append(sym)
            # methods + ORM relationships inside the class body
            for sub in stmt.body:
                if isinstance(sub, (ast.FunctionDef, ast.AsyncFunctionDef)):
                    if sub.name.startswith("__"):
                        continue
                    msig = f"{sub.name}({arg_names(sub.args, drop_self=True)})"
                    node.symbols.append(Symbol("method", f"{stmt.name}.{sub.name}", msig, sub.lineno))
                # relationship("Target") assignments
                val = None
                if isinstance(sub, ast.Assign):
                    val = sub.value
                elif isinstance(sub, ast.AnnAssign):
                    val = sub.value
                if isinstance(val, ast.Call):
                    fn = val.func
                    fn_name = fn.id if isinstance(fn, ast.Name) else (fn.attr if isinstance(fn, ast.Attribute) else "")
                    if fn_name == "relationship" and val.args:
                        tgt = _str_const(val.args[0])
                        if tgt:
                            node.rels.append(tgt)

    node.ext = sorted(r for r in ext_roots if r and not r.startswith("_"))
    return node, raw_imports


# --------------------------------------------------------------------------- #
# TypeScript analysis (regex, heuristic)
# --------------------------------------------------------------------------- #

RE_IMPORT_FROM = re.compile(r"""(?:import|export)\b[\s\S]*?from\s*['"]([^'"]+)['"]""")
RE_IMPORT_BARE = re.compile(r"""^\s*import\s*['"]([^'"]+)['"]""", re.M)
RE_EXP_FUNC = re.compile(r"""export\s+(?:default\s+)?(?:async\s+)?function\s+(\w+)\s*\(([^)]*)\)""")
RE_EXP_CLASS = re.compile(r"""export\s+(?:default\s+)?(?:abstract\s+)?class\s+(\w+)""")
RE_EXP_CONST = re.compile(r"""export\s+const\s+(\w+)""")
RE_EXP_TYPE = re.compile(r"""export\s+(?:default\s+)?(?:interface|type)\s+(\w+)""")
RE_EXP_DEFAULT = re.compile(r"""export\s+default\s+(\w+)\s*;""")


def analyze_ts(path: Path, rel: str, src: str) -> Tuple[Node, List[str]]:
    node = Node(id=rel, lang="ts", layer=detect_layer(rel, "ts"),
                loc=src.count("\n") + 1, tokens=max(1, len(src) // 4))
    is_tsx = path.suffix == ".tsx"

    raw_specs: List[str] = []
    ext_roots: Set[str] = set()
    for m in RE_IMPORT_FROM.finditer(src):
        spec = m.group(1)
        raw_specs.append(spec)
        if not spec.startswith(".") and not spec.startswith("@/"):
            ext_roots.add(spec.split("/")[0] if not spec.startswith("@") else spec.split("/")[0])
    for m in RE_IMPORT_BARE.finditer(src):
        raw_specs.append(m.group(1))

    def add(kind: str, name: str, sig: str = ""):
        node.symbols.append(Symbol(kind, name, sig))

    for m in RE_EXP_FUNC.finditer(src):
        name, params = m.group(1), m.group(2)
        clean = ", ".join(p.split(":")[0].strip() for p in params.split(",") if p.strip())
        if name.startswith("use") and len(name) > 3 and name[3].isupper():
            add("hook", name, f"{name}({clean})")
        else:
            add("func", name, f"{name}({clean})")
    for m in RE_EXP_CLASS.finditer(src):
        add("class", m.group(1))
    for m in RE_EXP_CONST.finditer(src):
        name = m.group(1)
        if name.startswith("use") and len(name) > 3 and name[3].isupper():
            add("hook", name)
        elif is_tsx and name[:1].isupper():
            add("component", name)
        else:
            add("const", name)
    for m in RE_EXP_TYPE.finditer(src):
        add("type", m.group(1))

    node.ext = sorted(r for r in ext_roots if r)
    return node, raw_specs


# --------------------------------------------------------------------------- #
# Graph construction (import resolution)
# --------------------------------------------------------------------------- #

def resolve_py_imports(specs, current_mod: str, mod_to_id: Dict[str, str]) -> Set[str]:
    out: Set[str] = set()
    for kind, mod, names, level, is_pkg in specs:
        if kind == "import":
            for m in names:
                if m in mod_to_id:
                    out.add(mod_to_id[m])
            continue
        # from ... import ...
        if level == 0:
            base = mod
        else:
            parts = current_mod.split(".") if current_mod else []
            if not is_pkg and parts:
                parts = parts[:-1]            # package of the current module
            up = level - 1
            if up > 0:
                parts = parts[:-up] if up <= len(parts) else []
            base = ".".join(parts)
            if mod:
                base = base + "." + mod if base else mod
        if base in mod_to_id:
            out.add(mod_to_id[base])
        for n in names:
            full = base + "." + n if base else n
            if full in mod_to_id:
                out.add(mod_to_id[full])
    return out


def resolve_ts_imports(specs, importer: Path, root: Path, ts_ids: Set[str],
                       src_roots: List[Path]) -> Set[str]:
    out: Set[str] = set()
    cand_exts = ["", ".ts", ".tsx", ".d.ts"]
    cand_index = ["/index.ts", "/index.tsx"]
    for spec in specs:
        bases: List[Path] = []
        if spec.startswith("."):
            bases.append((importer.parent / spec))
        elif spec.startswith("@/"):
            for sr in src_roots:
                bases.append(sr / spec[2:])
        else:
            continue
        resolved = None
        for base in bases:
            base = Path(os.path.normpath(str(base)))
            tries = [str(base) + e for e in cand_exts] + [str(base) + e for e in cand_index]
            for t in tries:
                tp = Path(t)
                try:
                    rid = tp.relative_to(root).as_posix()
                except ValueError:
                    continue
                if rid in ts_ids:
                    resolved = rid
                    break
            if resolved:
                break
        if resolved:
            out.add(resolved)
    return out


def pagerank(node_ids: List[str], edges: List[Tuple[str, str]],
             d: float = 0.85, iters: int = 50) -> Dict[str, float]:
    n = len(node_ids)
    if n == 0:
        return {}
    pr = {i: 1.0 / n for i in node_ids}
    incoming: Dict[str, List[str]] = {i: [] for i in node_ids}
    outdeg: Dict[str, int] = {i: 0 for i in node_ids}
    for a, b in edges:
        if a in outdeg and b in incoming:
            outdeg[a] += 1
            incoming[b].append(a)
    for _ in range(iters):
        dangling = sum(pr[i] for i in node_ids if outdeg[i] == 0)
        new = {}
        for i in node_ids:
            s = sum(pr[a] / outdeg[a] for a in incoming[i] if outdeg[a])
            new[i] = (1 - d) / n + d * (s + dangling / n)
        pr = new
    return pr


