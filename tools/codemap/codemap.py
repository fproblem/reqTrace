# Layer detection by path / filename ------------------------------------------------

def detect_layer(rel: str, lang: str) -> str:
    p = rel.replace("\\", "/")
    name = p.rsplit("/", 1)[-1]
    if lang == "py":
        if "/routers/" in p or p.endswith("/routers.py"):
            return "router"
        if "/services/" in p:
            return "service"
        if "/models/" in p:
            return "model"
        if "/schemas/" in p:
            return "schema"
        if name in ("main.py", "asgi.py", "wsgi.py", "app.py"):
            return "entry"
        if name in ("database.py", "config.py", "settings.py", "deps.py", "db.py"):
            return "infra"
        return "module"
    else:  # ts
        if "/pages/" in p:
            return "page"
        if "/hooks/" in p or name.startswith("use"):
            return "hook"
        if "/components/" in p:
            return "component"
        if "/api/" in p or name in ("client.ts", "api.ts"):
            return "api"
        if "/types" in p or name.startswith("types"):
            return "type"
        if "/styles/" in p or "token" in name:
            return "style"
        if name in ("index.tsx", "index.ts", "App.tsx", "main.tsx"):
            return "entry"
        return "module"


