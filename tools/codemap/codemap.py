def _mid(nid: str) -> str:
    return "n_" + re.sub(r"[^0-9a-zA-Z]", "_", nid)


def render_mermaid(cm: CodeMap, nodes: Optional[List[Node]] = None) -> str:
    nodes = nodes or list(cm.nodes.values())
    ids = {n.id for n in nodes}
    lines = ["flowchart LR"]
    used_layers: Set[str] = set()
    # group into subgraphs by lang+layer
    for lang, lang_label in (("py", "Backend"), ("ts", "Frontend")):
        lang_nodes = [n for n in nodes if n.lang == lang]
        if not lang_nodes:
            continue
        lines.append(f"  subgraph {lang_label}")
        lines.append("    direction TB")
        for layer in LAYER_ORDER:
            grp = [n for n in lang_nodes if n.layer == layer]
            if not grp:
                continue
            sgid = f"{lang}_{layer}"
            lines.append(f'    subgraph {sgid}["{LAYER_LABEL.get(layer, layer)}"]')
            for n in sorted(grp, key=lambda n: -n.rank):
                label = n.id.rsplit("/", 1)[-1]
                lines.append(f'      {_mid(n.id)}["{label}<br/>{n.loc} loc"]')
                used_layers.add(layer)
            lines.append("    end")
        lines.append("  end")
    # edges
    for a, b in cm.edges:
        if a in ids and b in ids:
            lines.append(f"  {_mid(a)} --> {_mid(b)}")
    # styling
    for layer in used_layers:
        cls = MERMAID_CLASSDEF.get(layer)
        if cls:
            lines.append(f"  classDef {layer} {cls};")
    for n in nodes:
        if n.layer in used_layers and n.layer in MERMAID_CLASSDEF:
            lines.append(f"  class {_mid(n.id)} {n.layer};")
    return "\n".join(lines)


def render_dot(cm: CodeMap, nodes: Optional[List[Node]] = None) -> str:
    nodes = nodes or list(cm.nodes.values())
    ids = {n.id for n in nodes}
    color = {
        "router": "#5b9dff", "service": "#a880ff", "model": "#f2b23d",
        "schema": "#34c0aa", "infra": "#828c9e", "entry": "#ff7088",
        "page": "#5b9dff", "component": "#828c9e", "hook": "#f2b23d",
        "api": "#34c0aa", "type": "#6f7889", "style": "#6f7889", "module": "#9aa3b2",
    }
    lines = ['digraph codemap {', '  rankdir=LR;', '  bgcolor="#0e1118";',
             '  node [shape=box style="rounded,filled" fontname="Helvetica" '
             'fontsize=10 color="#2a313f" fontcolor="#e7eaf0"];',
             '  edge [color="#3a4252" arrowsize=0.6];']
    for n in sorted(nodes, key=lambda n: n.id):
        fill = color.get(n.layer, "#23272f")
        label = n.id.rsplit("/", 1)[-1].replace('"', '')
        lines.append(f'  "{n.id}" [label="{label}\\n{n.loc} loc" '
                     f'fillcolor="{fill}22" color="{fill}"];')
    for a, b in cm.edges:
        if a in ids and b in ids:
            lines.append(f'  "{a}" -> "{b}";')
    lines.append("}")
    return "\n".join(lines)


# --------------------------------------------------------------------------- #
# Focus mode (neighborhood of a file)
# --------------------------------------------------------------------------- #

def focus(cm: CodeMap, query: str, depth: int = 1) -> str:
    matches = [n for n in cm.nodes.values() if query in n.id]
    if not matches:
        return f"No file matches '{query}'. Try a path fragment like 'pages.py' or 'DiffView'."
    seed = sorted(matches, key=lambda n: (-n.rank, n.id))[0]
    keep: Set[str] = {seed.id}
    frontier = {seed.id}
    for _ in range(depth):
        nxt: Set[str] = set()
        for nid in frontier:
            for a, b in cm.edges:
                if a == nid:
                    nxt.add(b)
                if b == nid:
                    nxt.add(a)
        nxt -= keep
        keep |= nxt
        frontier = nxt

    lines: List[str] = []
    A = lines.append
    A(f"# Focus: {seed.id}")
    A(f"_neighborhood, depth {depth} · {len(keep)} files_")
    A("")
    deps = sorted(b for (a, b) in cm.edges if a == seed.id)
    used = sorted(a for (a, b) in cm.edges if b == seed.id)
    A(f"**{seed.id}** · {seed.loc} loc · {seed.layer}")
    if seed.routes:
        A(f"- routes: {', '.join(seed.routes)}")
    if seed.symbols:
        A(f"- defs: {', '.join(s.sig or s.name for s in seed.symbols[:12])}")
    A(f"- imports ({len(deps)}): {', '.join(deps) or '—'}")
    A(f"- used-by ({len(used)}): {', '.join(used) or '—'}")
    A("")
    A("## Neighborhood")
    sub = [cm.nodes[i] for i in keep]
    for lang_label, layer_label, group in _grouped(sub):
        for n in group:
            mark = " ← FOCUS" if n.id == seed.id else ""
            A(f"- `{n.id}` · {n.layer} · {n.loc} loc · ↓{n.fan_in} ↑{n.fan_out}{mark}")
    A("")
    A("## Mermaid")
    A("```mermaid")
    sub_cm = CodeMap(cm.root)
    sub_cm.nodes = {i: cm.nodes[i] for i in keep}
    sub_cm.edges = [(a, b) for (a, b) in cm.edges if a in keep and b in keep]
    A(render_mermaid(sub_cm, sub))
    A("```")
    return "\n".join(lines)


