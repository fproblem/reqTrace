# --------------------------------------------------------------------------- #
# Data model
# --------------------------------------------------------------------------- #

@dataclass
class Symbol:
    kind: str          # class | func | method | route | component | hook | type | const
    name: str
    sig: str = ""
    line: int = 0
    extra: str = ""    # e.g. base classes, route method


@dataclass
class Node:
    id: str            # path relative to root, posix style
    lang: str          # py | ts
    layer: str
    loc: int
    tokens: int                       # rough token estimate of the source
    symbols: List[Symbol] = field(default_factory=list)
    routes: List[str] = field(default_factory=list)      # "GET /api/pages"
    rels: List[str] = field(default_factory=list)        # ORM relationship targets
    ext: List[str] = field(default_factory=list)         # external top-level deps
    imports: List[str] = field(default_factory=list)     # resolved internal node ids
    is_script: bool = False                              # has `if __name__ == "__main__"`
    # filled later
    fan_in: int = 0
    fan_out: int = 0
    rank: float = 0.0


# --------------------------------------------------------------------------- #
# File discovery
# --------------------------------------------------------------------------- #

def discover(root: Path, exclude_dirs: Set[str], exclude_frags: Set[str]) -> List[Path]:
    files: List[Path] = []
    for dirpath, dirnames, filenames in os.walk(root):
        # prune excluded directories in-place
        dirnames[:] = [d for d in dirnames if d not in exclude_dirs]
        for fn in filenames:
            ext = os.path.splitext(fn)[1]
            if ext not in PY_EXT and ext not in TS_EXT:
                continue
            full = Path(dirpath) / fn
            rel = full.relative_to(root).as_posix()
            if any(frag in rel or frag in fn for frag in exclude_frags):
                continue
            if fn.endswith(".d.ts"):
                continue
            files.append(full)
    return sorted(files)


def read_text(path: Path) -> str:
    try:
        return path.read_text(encoding="utf-8")
    except UnicodeDecodeError:
        return path.read_text(encoding="utf-8", errors="replace")
    except Exception:
        return ""


