#!/usr/bin/env python3
"""
codemap — zero-dependency code map generator.

Builds a dependency graph of a Python + TypeScript project and emits:
  - repomap.md   : a compact, ranked, LLM-friendly map (read one file instead of forty)
  - graph.json   : full structured data (nodes, edges, symbols, routes, ranks)
  - graph.mmd    : a Mermaid diagram (renders in Markdown/GitHub, no graphviz needed)
  - graph.dot    : Graphviz source (+ graph.svg if `dot` is installed)

Python is parsed with the stdlib `ast` module (exact). TypeScript/TSX is parsed
with lightweight regexes (heuristic, good enough for a navigation map).

Usage:
  python tools/codemap/codemap.py                       # full run -> tools/codemap/out/
  python tools/codemap/codemap.py --focus pages.py      # neighborhood of a file -> stdout
  python tools/codemap/codemap.py --format json,mermaid # only some outputs
  python tools/codemap/codemap.py --root . --out build/codemap

Requires only the Python standard library (3.8+).
"""

