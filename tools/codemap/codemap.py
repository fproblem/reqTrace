def main(argv=None):
    parser = argparse.ArgumentParser(
        description="Generate a code map (dependency graph + LLM repo map).")
    here = Path(__file__).resolve()
    default_root = here.parents[2] if len(here.parents) >= 3 else Path.cwd()
    parser.add_argument("--root", default=str(default_root),
                        help="project root to scan (default: repo root)")
    parser.add_argument("--out", default=str(here.parent / "out"),
                        help="output directory")
    parser.add_argument("--format", default="md,json,mermaid,dot",
                        help="comma list: md,json,mermaid,dot")
    parser.add_argument("--focus", default=None,
                        help="print the neighborhood of a file (by path fragment) to stdout")
    parser.add_argument("--depth", type=int, default=1, help="focus depth (default 1)")
    parser.add_argument("--exclude", default="",
                        help="extra comma-separated directory names to exclude")
    args = parser.parse_args(argv)

    root = Path(args.root).resolve()
    if not root.exists():
        print(f"error: root does not exist: {root}", file=sys.stderr)
        return 2

    exclude_dirs = set(DEFAULT_EXCLUDE_DIRS)
    exclude_dirs.update(d.strip() for d in args.exclude.split(",") if d.strip())

    files = discover(root, exclude_dirs, DEFAULT_EXCLUDE_FRAGMENTS)
    cm = CodeMap(root)
    cm.build(files)

    if args.focus:
        print(focus(cm, args.focus, args.depth))
        return 0

    out = Path(args.out)
    out.mkdir(parents=True, exist_ok=True)
    fmts = {f.strip() for f in args.format.split(",") if f.strip()}
    written: List[str] = []

    if "md" in fmts:
        (out / "repomap.md").write_text(render_repomap(cm), encoding="utf-8")
        written.append("repomap.md")
    if "json" in fmts:
        (out / "graph.json").write_text(render_json(cm), encoding="utf-8")
        written.append("graph.json")
    if "mermaid" in fmts:
        (out / "graph.mmd").write_text(render_mermaid(cm), encoding="utf-8")
        written.append("graph.mmd")
    if "dot" in fmts:
        dot_src = render_dot(cm)
        (out / "graph.dot").write_text(dot_src, encoding="utf-8")
        written.append("graph.dot")
        dot_bin = shutil.which("dot")
        if dot_bin:
            try:
                subprocess.run([dot_bin, "-Tsvg", str(out / "graph.dot"),
                                "-o", str(out / "graph.svg")], check=True,
                               capture_output=True, timeout=60)
                written.append("graph.svg")
            except Exception as e:
                print(f"note: graphviz present but render failed: {e}", file=sys.stderr)

    st = cm.stats()
    print(f"codemap: {st['files']} files, {st['edges']} edges, {st['loc']:,} LOC")
    print(f"  source ≈ {st['source_tokens_est']:,} tokens")
    print(f"  hotspots: {', '.join(n.id for n in cm.hotspots()) or '—'}")
    orph = cm.orphans()
    if orph:
        print(f"  unreferenced: {', '.join(n.id for n in orph)}")
    print(f"  wrote {len(written)} file(s) to {out}: {', '.join(written)}")
    if "dot" in fmts and not shutil.which("dot"):
        print("  (install graphviz for graph.svg: `brew install graphviz`)")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
